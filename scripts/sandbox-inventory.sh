#!/usr/bin/env bash
# T0.3 - Re-runnable inventory of the strix-sandbox image.
# Runs the image offline (--network none, --rm) and records every
# security-relevant binary, its absolute path, a version line, PATH order and
# language runtimes. Output: docs/sandbox-inventory.md
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
IMAGE="${1:-ghcr.io/usestrix/strix-sandbox:1.4.1}"
OUT="$ROOT/docs/sandbox-inventory.md"

run_docker() {
  if docker info >/dev/null 2>&1; then docker "$@"; return; fi
  { printf 'exec docker'; for a in "$@"; do printf ' %q' "$a"; done; printf '\n'; } | newgrp docker
}

PROBE=$(cat <<'EOS'
set +e
echo "##PATH $PATH"
echo "##USER $(id -un) uid=$(id -u)"
for t in nmap masscan rustscan naabu zmap ffuf gobuster feroxbuster dirb dirsearch wfuzz \
         sqlmap ghauri nuclei nikto wpscan whatweb wafw00f httpx katana gau waybackurls \
         subfinder amass dnsx dig host whois hydra medusa ncrack patator john hashcat \
         jwt_tool commix xsstrike dalfox arjun paramspider testssl.sh sslscan sslyze \
         trufflehog gitleaks semgrep bandit msfconsole searchsploit netcat nc ncat socat \
         curl wget httpie tcpdump tshark hping3 slowhttptest siege ab wrk vegeta \
         interactsh-client caido caido-cli agent-browser chromium playwright \
         python3 node npm perl ruby go java php bash sh; do
  p=$(command -v "$t" 2>/dev/null)
  if [ -n "$p" ]; then
    real=$(readlink -f "$p")
    v=$( (timeout 5 "$t" --version 2>&1 || timeout 5 "$t" -version 2>&1 || timeout 5 "$t" -V 2>&1) | grep -v '^\s*$' | head -1 | cut -c1-90)
    echo "##TOOL $t|$p|$real|$v"
  else
    echo "##MISSING $t"
  fi
done
for d in $(echo "$PATH" | tr ':' ' '); do [ -d "$d" ] && echo "##DIRCOUNT $d $(ls "$d" 2>/dev/null | wc -l)"; done
pip list 2>/dev/null | grep -i -E "impacket|pwntools|requests|scapy|paramiko|playwright|selenium|mitmproxy" | sed 's/^/##PIP /'
EOS
)

RAW=$(run_docker run --rm --network none --entrypoint bash "$IMAGE" -lc "$PROBE")

{
  echo "# strix-sandbox tool inventory"
  echo
  echo "Generated by \`scripts/sandbox-inventory.sh\` on $(date -u +%Y-%m-%dT%H:%MZ) from \`$IMAGE\`"
  echo "(image run offline: \`--network none --rm\`). Re-run the script to refresh."
  echo
  echo "- PATH order: \`$(echo "$RAW" | sed -n 's/^##PATH //p')\`"
  echo "- Runs as: \`$(echo "$RAW" | sed -n 's/^##USER //p')\`"
  echo
  echo "## Present"
  echo
  echo "| Tool | Resolved path | Real path | Version line |"
  echo "|---|---|---|---|"
  echo "$RAW" | sed -n 's/^##TOOL //p' | while IFS='|' read -r t p r v; do
    v=${v//|/\\|}; echo "| \`$t\` | \`$p\` | \`$r\` | ${v} |"; done
  echo
  echo "## Absent (probed, not installed)"
  echo
  echo "$RAW" | sed -n 's/^##MISSING //p' | sed 's/.*/`&`/' | paste -sd ' ' -
  echo
  echo "## Python security libraries"
  echo
  echo "$RAW" | sed -n 's/^##PIP /- /p'
  echo
  echo "## PATH directories (entry counts)"
  echo
  echo "$RAW" | sed -n 's/^##DIRCOUNT /- /p'
} > "$OUT"
echo "wrote $OUT"
